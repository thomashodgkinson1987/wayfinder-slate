#!/usr/bin/env node
/**
 * Build the treasure chest section of the map-object dataset.
 *
 * The committed dataset (`frontend/static/data/map_objects.json`) joins save
 * flag names with map marker positions for every tracked object type. Treasure
 * chests are joined by CRC32 save-flag hash instead of by name, because the
 * chest flags are named after their placement id
 * (`MainField_TBox_Field_<base>_<placement_id>`, plus the 55 variant chests
 * with their full suffix) and no public table maps those names back to the
 * marker positions.
 *
 * Inputs:
 *   - `scripts/treasure-flags.json` — committed hash -> marker id table.
 *   - `frontend/static/map/botw/markers/treasures.json` — the upstream Zelda
 *     Dungeon treasure markers, fetched by `scripts/fetch-map-assets.sh` at the
 *     pinned commit.
 *
 * Outputs:
 *   - the `treasures` array and `source.treasures` entry in the dataset;
 *   - `crates/wayfinder-save/src/treasure_hashes.rs`, the save-flag hashes the
 *     Rust save parser counts opened chests from.
 *
 * The upstream marker coordinates use Zelda Dungeon's map space, which is the
 * game space rotated 90 degrees and scaled by two: `mapX = -2 * gameZ` and
 * `mapY = 2 * gameX`. The dataset stores game coordinates, so the transform is
 * inverted here: `x = mapY / 2`, `z = -mapX / 2`.
 *
 * Run with `node scripts/build-treasure-objects.mjs` after fetching the map
 * assets. The outputs are committed, so this only needs to run when the pinned
 * upstream revision or the flag table changes.
 */
import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const FLAGS_PATH = path.join(ROOT, 'scripts', 'treasure-flags.json');
const UPSTREAM_PATH = path.join(
  ROOT,
  'frontend',
  'static',
  'map',
  'botw',
  'markers',
  'treasures.json',
);
const DATASET_PATH = path.join(ROOT, 'frontend', 'static', 'data', 'map_objects.json');
const RUST_PATH = path.join(ROOT, 'crates', 'wayfinder-save', 'src', 'treasure_hashes.rs');

/** Expected number of tracked chests: 1315 placements minus 3 gambling chests. */
const EXPECTED_TREASURES = 1312;
/** Chests in the casino gambling mini-game. They have no save flag at all. */
const GAMBLE_CHESTS = ['Treasure0055', 'Treasure0056', 'Treasure0057'];
/** The dataset stores game coordinates; the validator rejects anything wider. */
const COORDINATE_LIMIT = 6000;

const SOURCE_ATTRIBUTION =
  'marcrobledo/savegame-editors (MIT) chest flags + Zelda Dungeon treasure markers';

async function readJson(file) {
  return JSON.parse(await readFile(file, 'utf8'));
}

/**
 * Flatten the upstream layer-group document into marker entries.
 * Each layer holds one or more sub-layers, each with its own marker list.
 */
function flattenUpstreamLayers(document) {
  const markers = [];
  for (const layer of Object.values(document)) {
    if (!layer || !Array.isArray(layer.layers)) continue;
    for (const subLayer of layer.layers) {
      for (const marker of subLayer.markers ?? []) {
        markers.push({ ...marker, group: layer.name });
      }
    }
  }
  return markers;
}

/** Convert a Zelda Dungeon map coordinate to the dataset's game x/z. */
function toGameCoordinates([mapX, mapY]) {
  return { x: mapY / 2, z: -mapX / 2 };
}

function formatRustHash(hash) {
  const hex = hash.toString(16).padStart(8, '0');
  return `0x${hex.slice(0, 4)}_${hex.slice(4)}`;
}

function buildRustSource(hashes) {
  const lines = hashes.map((hash) => `    ${formatRustHash(hash)},`).join('\n');
  return `//! CRC32 hashes of the treasure chest save flags.
//!
//! Generated by \`scripts/build-treasure-objects.mjs\` from
//! \`scripts/treasure-flags.json\`. Do not edit by hand.
//!
//! The 1315 static \`MainField_TBox_Field_*\` chest placements include three
//! casino gambling mini-game chests, which have no save flag. Those three are
//! not tracked, so a save can report at most ${EXPECTED_TREASURES} opened chests.

/// Number of treasure chests tracked by the save flags.
pub const TREASURE_TOTAL: usize = ${EXPECTED_TREASURES};

/// CRC32 hashes of the tracked treasure chest save flags, in ascending order.
pub const TREASURE_HASHES: &[u32] = &[
${lines}
];
`;
}

async function main() {
  const flagsDocument = await readJson(FLAGS_PATH);
  const flagEntries = Object.entries(flagsDocument.treasure ?? {}).map(([hash, markerId]) => [
    Number(hash),
    markerId,
  ]);

  if (flagEntries.length !== EXPECTED_TREASURES) {
    throw new Error(
      `expected ${EXPECTED_TREASURES} chest flags, found ${flagEntries.length}`,
    );
  }

  const hashByMarkerId = new Map();
  for (const [hash, markerId] of flagEntries) {
    if (hashByMarkerId.has(markerId)) {
      throw new Error(`duplicate marker id in flag table: ${markerId}`);
    }
    hashByMarkerId.set(markerId, hash);
  }

  const upstream = await readJson(UPSTREAM_PATH);
  const upstreamMarkers = flattenUpstreamLayers(upstream);

  const treasures = [];
  for (const marker of upstreamMarkers) {
    const hash = hashByMarkerId.get(marker.id);
    if (hash === undefined) continue;

    if (!Array.isArray(marker.coords) || marker.coords.length !== 2) {
      throw new Error(`${marker.id}: expected a [mapX, mapY] coordinate pair`);
    }
    const { x, z } = toGameCoordinates(marker.coords);
    if (!Number.isFinite(x) || !Number.isFinite(z)) {
      throw new Error(`${marker.id}: non-finite coordinate`);
    }
    if (Math.abs(x) > COORDINATE_LIMIT || Math.abs(z) > COORDINATE_LIMIT) {
      throw new Error(`${marker.id}: coordinate outside the game world`);
    }
    if (typeof marker.name !== 'string' || marker.name.trim() === '') {
      throw new Error(`${marker.id}: missing name`);
    }
    if (typeof marker.group !== 'string' || marker.group.trim() === '') {
      throw new Error(`${marker.id}: missing group`);
    }

    treasures.push({
      id: marker.id,
      name: marker.name,
      group: marker.group,
      x,
      z,
      ...(Array.isArray(marker.tags) ? { tags: marker.tags } : {}),
    });
  }

  if (treasures.length !== EXPECTED_TREASURES) {
    throw new Error(
      `expected ${EXPECTED_TREASURES} treasure markers, found ${treasures.length}`,
    );
  }

  for (const gamble of GAMBLE_CHESTS) {
    if (treasures.some((treasure) => treasure.id === gamble)) {
      throw new Error(`${gamble} is a gambling chest and must not be tracked`);
    }
  }

  const ids = new Set(treasures.map((treasure) => treasure.id));
  if (ids.size !== treasures.length) {
    throw new Error('duplicate treasure marker ids');
  }

  const dataset = await readJson(DATASET_PATH);
  dataset.version = 2;
  dataset.source = { ...dataset.source, treasures: SOURCE_ATTRIBUTION };
  dataset.treasures = treasures;

  await writeFile(DATASET_PATH, `${JSON.stringify(dataset)}\n`);

  const hashes = flagEntries.map(([hash]) => hash).sort((a, b) => a - b);
  await writeFile(RUST_PATH, buildRustSource(hashes));

  console.log(
    `Wrote ${treasures.length} treasure markers to ${path.relative(ROOT, DATASET_PATH)} ` +
      `and ${hashes.length} save-flag hashes to ${path.relative(ROOT, RUST_PATH)}.`,
  );
}

main().catch((error) => {
  console.error(`\nerror: ${error.message}`);
  process.exitCode = 1;
});
